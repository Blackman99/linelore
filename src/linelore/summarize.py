"""--summarize: hand the facts to a model command the user configured.

linelore has no model, no API key and makes no network call for this. It runs
the user's own command (``--summarize-cmd`` or ``LINELORE_SUMMARIZE_CMD``),
writes a prompt plus the plain-text lore to its stdin and shows whatever it
prints, labelled as a model-generated summary and kept apart from the facts.
"""
import os
import re
import shlex
import shutil
import signal
import subprocess
import textwrap

ENV_CMD = "LINELORE_SUMMARIZE_CMD"
ENV_PROMPT = "LINELORE_SUMMARIZE_PROMPT"
ENV_TIMEOUT = "LINELORE_SUMMARIZE_TIMEOUT"
DEFAULT_TIMEOUT = 120.0
MAX_CHARS = 4000

PROMPT = (
    "Below is what linelore found for a line of code: the commit that last changed it, the pull request "
    "(or merge request) that merged it, the issues it closed and review comments near the line.\n"
    "In 2-4 sentences, explain why the code is the way it is. Use only these facts and cite them "
    "(#PR, #issue, @reviewer). If they don't explain the reason, say so plainly. Do not guess."
)

DISCLAIMER = ("Generated by a model command you configured, from linelore's facts. It may be wrong; "
              "it is not one of linelore's facts.")

_ANSI = re.compile(r"\x1b\[[0-?]*[ -/]*[@-~]|\x1b\][^\x07\x1b]*(?:\x07|\x1b\\)|\x1b[@-_]")
_CTRL = re.compile(r"[\x00-\x08\x0b-\x1f\x7f]")


class SummarizeError(Exception):
    """The summary could not be made; the facts are still printed."""


class SummarizeConfigError(SummarizeError):
    """--summarize without a usable command: a usage error, caught before any work."""


def resolve_command(flag_cmd, environ=None):
    """(argv, source) for the configured command, or raise SummarizeConfigError."""
    environ = os.environ if environ is None else environ
    if flag_cmd is not None:
        raw, source = flag_cmd, "--summarize-cmd"
    else:
        raw, source = environ.get(ENV_CMD, ""), ENV_CMD
    if not raw.strip():
        if flag_cmd is not None:
            raise SummarizeConfigError("--summarize-cmd is empty")
        raise SummarizeConfigError(
            "--summarize needs a command to send the lore to, and linelore has no model of its own. "
            "Pass --summarize-cmd 'llm -m gpt-4o-mini' (or any command that reads a prompt on stdin) "
            "or set %s." % ENV_CMD)
    try:
        argv = shlex.split(raw, posix=os.name != "nt")
    except ValueError as e:
        raise SummarizeConfigError("can't parse %s %r: %s" % (source, raw, e))
    if os.name == "nt":  # non-POSIX shlex keeps the quotes
        argv = [t[1:-1] if len(t) > 1 and t[0] == t[-1] and t[0] in "\"'" else t for t in argv]
    return argv, source


def program_name(argv):
    """The name shown in the label: just the program, never its arguments (they may hold secrets)."""
    name = os.path.basename(argv[0]) or argv[0]
    return re.sub(r"(?i)\.(exe|cmd|bat)$", "", name)


def timeout_from_env(environ=None):
    environ = os.environ if environ is None else environ
    try:
        t = float(environ.get(ENV_TIMEOUT, ""))
    except ValueError:
        return DEFAULT_TIMEOUT
    return t if 0 < t < float("inf") else DEFAULT_TIMEOUT


def build_input(facts_text, environ=None):
    environ = os.environ if environ is None else environ
    prompt = environ.get(ENV_PROMPT, PROMPT)
    head = prompt.rstrip() + "\n\n" if prompt.strip() else ""
    return head + "--- linelore output ---\n" + facts_text.rstrip() + "\n"


_BACK = re.compile(r"\x1b\[(\d*)D|\x08")


def _apply_cursor_back(text):
    """Honour cursor-left moves and backspaces instead of just dropping them.

    Some model CLIs (ollama run, for one) word-wrap a streamed answer by
    moving the cursor back over a half-printed word and printing it again on
    the next line; stripping the escapes alone would leave "bu\nbug". That
    soft wrap is undone too, so linelore can wrap the text to its own width.
    """
    if "\x1b[" not in text and "\x08" not in text:
        return text
    out, pos = [], 0
    for m in _BACK.finditer(text):
        out.append(text[pos:m.start()])
        n = 1 if m.group(0) == "\x08" else int(m.group(1) or 1)
        joined = "".join(out)
        line_start = joined.rfind("\n") + 1
        cut = max(line_start, len(joined) - n)
        out = [joined[:cut]]
        pos = m.end()
        rest = re.match(r"(?:\x1b\[0?K)?\n", text[pos:])
        if rest and n > 0 and m.group(0) != "\x08":
            # erase-then-newline is the CLI's own soft wrap, not a paragraph break
            out = [out[0].rstrip(" ") + " "]
            pos += rest.end()
    out.append(text[pos:])
    return "".join(out)


def clean(text):
    """Strip terminal escapes and control characters, trim, cap the length."""
    text = _ANSI.sub("", _apply_cursor_back(text.replace("\r\n", "\n")))
    text = _CTRL.sub("", text).strip()
    text = re.sub(r"\n{3,}", "\n\n", text)
    if len(text) > MAX_CHARS:
        text = text[: MAX_CHARS - 1].rstrip() + "…"
    return text


def _kill(p):
    try:
        if os.name != "nt":
            os.killpg(p.pid, signal.SIGKILL)  # the whole group: wrappers often spawn the real model CLI
        else:
            p.kill()
    except (OSError, ProcessLookupError):
        pass


def run(argv, source, facts_text, timeout=None, environ=None):
    """Run the user's command with the prompt + facts on stdin; return its cleaned stdout."""
    name = program_name(argv)
    timeout = timeout_from_env(environ) if timeout is None else timeout
    exe = shutil.which(argv[0])
    if exe is None:
        raise SummarizeError("`%s` (from %s) is not installed or not on PATH" % (argv[0], source))
    data = build_input(facts_text, environ).encode("utf-8")
    kw = {"start_new_session": True} if os.name != "nt" else {}
    try:
        p = subprocess.Popen([exe] + argv[1:], stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                             stderr=subprocess.PIPE, **kw)
    except OSError as e:
        raise SummarizeError("could not start `%s` (from %s): %s" % (name, source, e.strerror or e))
    try:
        out, err = p.communicate(data, timeout=timeout)
    except KeyboardInterrupt:
        _kill(p)  # it runs in its own session, so Ctrl-C has to be passed on by hand
        raise
    except subprocess.TimeoutExpired:
        _kill(p)
        p.communicate()
        raise SummarizeError("`%s` gave no answer within %s s, so linelore stopped it (%s=SECONDS to wait longer)"
                             % (name, ("%g" % timeout), ENV_TIMEOUT))
    if p.returncode != 0:
        tail = clean(err.decode("utf-8", "replace")).splitlines()
        why = ": " + textwrap.shorten(" ".join(tail[-3:]), 300, placeholder="…") if tail else ""
        raise SummarizeError("`%s` exited with status %d%s" % (name, p.returncode, why))
    text = clean(out.decode("utf-8", "replace"))
    if not text:
        raise SummarizeError("`%s` printed nothing on stdout" % name)
    return text


def as_json(name, text=None, error=None):
    """The explicitly labelled `model_summary` field; never mixed into the facts."""
    return {"by": name, "text": text, "error": error, "disclaimer": DISCLAIMER}


def to_text(name, text, color=False, width=None):
    """The labelled block printed after the facts."""
    def c(code, s):
        return "\033[%sm%s\033[0m" % (code, s) if color else s
    out = ["", c("1", "Summary") + " (generated by %s, may be wrong; not checked by linelore)" % name]
    for para in text.split("\n"):
        if not para.strip():
            out.append("")
            continue
        if width and width - 2 >= 30:
            out.extend("  " + ln for ln in textwrap.wrap(para, width - 2, break_long_words=False,
                                                         break_on_hyphens=False) or [""])
        else:
            out.append("  " + para)
    return "\n".join(out)
