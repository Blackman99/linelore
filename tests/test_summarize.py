"""--summarize: opt-in, labelled, kept out of the facts, and never fatal for them."""
import json
import os
import subprocess
import sys
import time

import pytest

from linelore import cli
from linelore import summarize as summ

FAKE = r'''
import os, sys, time
data = sys.stdin.buffer.read().decode("utf-8")
log = os.environ.get("FAKE_LLM_LOG")
if log:
    open(log, "w", encoding="utf-8").write(data)
mode = os.environ.get("FAKE_LLM_MODE", "ok")
if mode == "fail":
    sys.stderr.write("warming up\nError: model 'gpt-9' not found\n")
    sys.exit(7)
if mode == "slow":
    time.sleep(30)
if mode == "empty":
    sys.exit(0)
if mode == "ansi":
    sys.stdout.write("\x1b[31mRounded\x1b[0m per line\x07 (#790).\n")
    sys.exit(0)
print("Rounded per line so carts stop drifting by a cent (#790); @ops-lead called it the minimal fix.")
'''


def q(p):
    return '"%s"' % p if os.name == "nt" else "'%s'" % p


@pytest.fixture
def fake(tmp_path, monkeypatch):
    script = tmp_path / "fake_llm.py"
    script.write_text(FAKE, encoding="utf-8")
    log = tmp_path / "stdin.txt"
    monkeypatch.setenv("FAKE_LLM_LOG", str(log))
    monkeypatch.delenv(summ.ENV_CMD, raising=False)
    monkeypatch.delenv(summ.ENV_PROMPT, raising=False)
    monkeypatch.delenv(summ.ENV_TIMEOUT, raising=False)
    cmd = "%s %s" % (q(sys.executable), q(str(script)))
    return cmd, log


def test_not_run_unless_asked(fake, capsys, monkeypatch):
    cmd, log = fake
    monkeypatch.setenv(summ.ENV_CMD, cmd)  # configured, but --summarize not passed
    assert cli.main(["demo", "--json"]) == 0
    out = json.loads(capsys.readouterr().out)
    assert "model_summary" not in out
    assert not log.exists()


def test_needs_a_configured_command(fake, capsys):
    with pytest.raises(SystemExit) as e:
        cli.main(["demo", "--summarize"])
    assert e.value.code == 2
    err = capsys.readouterr().err
    assert "--summarize-cmd" in err and summ.ENV_CMD in err and "no model of its own" in err


def test_bad_quoting_is_a_usage_error(fake, capsys):
    with pytest.raises(SystemExit) as e:
        cli.main(["demo", "--summarize-cmd", "llm -s 'unclosed"])
    assert e.value.code == 2
    assert "can't parse --summarize-cmd" in capsys.readouterr().err


def test_text_summary_is_labelled_and_after_the_facts(fake, capsys):
    cmd, log = fake
    assert cli.main(["demo", "--no-color", "--summarize-cmd", cmd]) == 0
    out = capsys.readouterr().out
    facts, _, summary = out.partition("\nSummary (generated by ")
    assert "PR #812" in facts and "Rounded per line" not in facts
    assert summary.startswith(summ.program_name([sys.executable]) + ", may be wrong; not checked by linelore)")
    assert "Rounded per line so carts stop drifting" in summary
    sent = log.read_text(encoding="utf-8")
    assert sent.startswith(summ.PROMPT)
    assert "--- linelore output ---\nsrc/cart.py:42" in sent and "PR #812" in sent
    assert "\x1b[" not in sent  # the model gets plain text


def test_env_command_with_flag(fake, capsys, monkeypatch):
    cmd, log = fake
    monkeypatch.setenv(summ.ENV_CMD, cmd)
    assert cli.main(["demo", "--no-color", "--summarize"]) == 0
    assert "Rounded per line" in capsys.readouterr().out and log.exists()


def test_json_summary_is_a_separate_labelled_field(fake, capsys):
    cmd, _ = fake
    assert cli.main(["demo", "--json"]) == 0
    plain = json.loads(capsys.readouterr().out)
    assert cli.main(["demo", "--json", "--summarize-cmd", cmd]) == 0
    out = json.loads(capsys.readouterr().out)
    ms = out.pop("model_summary")
    assert out == plain  # the facts are untouched
    assert ms["text"].startswith("Rounded per line") and ms["error"] is None
    assert ms["by"] == summ.program_name([sys.executable])
    assert "may be wrong" in ms["disclaimer"] and "not one of linelore's facts" in ms["disclaimer"]


