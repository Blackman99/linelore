def test_real_repo_offline_with_summary(fake, tmp_path, capsys):
    cmd, log = fake
    repo = tmp_path / "r"
    repo.mkdir()
    for args in (["init", "-q"], ["config", "user.email", "a@e"], ["config", "user.name", "Ada"]):
        subprocess.run(["git"] + args, cwd=repo, check=True)
    (repo / "f.txt").write_text("one\ntwo\n")
    subprocess.run(["git", "add", "."], cwd=repo, check=True)
    subprocess.run(["git", "commit", "-qm", "add f"], cwd=repo, check=True)
    assert cli.main([str(repo / "f.txt") + ":1-2", "--offline", "--json", "--summarize-cmd", cmd]) == 0
    out = json.loads(capsys.readouterr().out)
    assert out["model_summary"]["text"] and out["commits"][0]["blame"]["summary"] == "add f"
    assert "add f" in log.read_text(encoding="utf-8")


def test_helpers():
    assert summ.program_name(["/usr/local/bin/llm", "-m", "secret-model", "--key", "sk-123"]) == "llm"
    assert summ.program_name([r"C:\tools\ollama.exe", "run"]) in ("ollama", r"C:\tools\ollama")
    assert summ.timeout_from_env({summ.ENV_TIMEOUT: "nan"}) == summ.DEFAULT_TIMEOUT
    assert summ.timeout_from_env({summ.ENV_TIMEOUT: "-1"}) == summ.DEFAULT_TIMEOUT
    assert summ.timeout_from_env({summ.ENV_TIMEOUT: "9"}) == 9
    assert summ.clean("a\r\n\n\n\nb\x1b]8;;http://x\x07c") == "a\n\nbc"
    assert len(summ.clean("x" * 10000)) == summ.MAX_CHARS
    text = summ.to_text("llm", "first para\n\nsecond", width=80)
    assert text.splitlines() == ["", "Summary (generated by llm, may be wrong; not checked by linelore)",
                                 "  first para", "", "  second"]


def test_word_wrap_redraws_are_undone():
    # bytes as `ollama run` streams them when it re-wraps a half-printed word
    raw = "providing water for drinking, a\x1b[1D\x1b[K\nagriculture, and the long\x1b[4D\x1b[K\nlongest r\x08iver."
    assert summ.clean(raw) == "providing water for drinking, agriculture, and the longest iver."
    assert summ.clean("\x1b[1mbold\x1b[0m") == "bold"
    assert summ.clean("ab\n\x1b[5Dc") == "ab\nc"  # never deletes across a line break
