def test_timeout(fake, capsys, monkeypatch):
    cmd, _ = fake
    monkeypatch.setenv("FAKE_LLM_MODE", "slow")
    monkeypatch.setenv(summ.ENV_TIMEOUT, "0.5")
    t = time.monotonic()
    assert cli.main(["demo", "--no-color", "--summarize-cmd", cmd]) == 4
    assert time.monotonic() - t < 15
    err = capsys.readouterr().err
    assert "gave no answer within 0.5 s" in err and summ.ENV_TIMEOUT in err


